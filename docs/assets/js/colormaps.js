function turbo(t) {
  const r = 0.13572138 + t * (4.61539260 + t * (-42.66032258 + t * (132.13108234 + t * (-152.94239396 + t * 59.28637943))));
  const g = 0.09140261 + t * (2.19418839 + t * (4.84296658 + t * (-14.18503333 + t * (4.27729857 + t * 2.82956604))));
  const b = 0.10667330 + t * (12.64194608 + t * (-60.58204836 + t * (110.36276771 + t * (-89.90310912 + t * 27.34824973))));
  return [r, g, b];
}
const clamp = (x) => Math.max(0, Math.min(1, x));
export const NAMES = ['magma', 'inferno', 'viridis', 'turbo'];
const cache = {};
export function lut(name) {
  if (cache[name]) return cache[name];
  const out = new Uint8Array(256 * 3);
  for (let i = 0; i < 256; i++) {
    const t = i / 255;
    const c = name === 'turbo' ? turbo(t) : [poly(C[name].r, t), poly(C[name].g, t), poly(C[name].b, t)];
    out[i * 3] = Math.round(clamp(c[0]) * 255); out[i * 3 + 1] = Math.round(clamp(c[1]) * 255); out[i * 3 + 2] = Math.round(clamp(c[2]) * 255);
  }
  return (cache[name] = out);
}
export function hexToRgb(h) { const v = parseInt(h.slice(1), 16); return [(v >> 16) & 255, (v >> 8) & 255, v & 255]; }
export function gradientCss(name) {
  const L = lut(name), stops = [];
  for (let i = 0; i <= 8; i++) { const k = Math.round(i / 8 * 255) * 3; stops.push(`rgb(${L[k]},${L[k + 1]},${L[k + 2]}) ${i * 12.5}%`); }
  return `linear-gradient(90deg,${stops.join(',')})`;
}
