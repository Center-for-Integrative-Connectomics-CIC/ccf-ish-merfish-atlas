// Perceptual colour maps as 256-entry RGB LUTs (polynomial fits of matplotlib viridis / magma / inferno and
// Google's turbo), plus helpers.
function poly(c, t) { let r = 0; for (let i = c.length - 1; i >= 0; i--) r = r * t + c[i]; return r; }
// coefficients (Matt Zucker, "colormap polynomials"): c0..c6 for r, g, b
